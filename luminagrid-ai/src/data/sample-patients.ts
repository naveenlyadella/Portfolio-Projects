export function generateMockPatients(count: number = 20): Patient[] {
  const complaints = [
    'Chest pain', 'Shortness of breath', 'Abdominal pain', 'Head injury',
    'Laceration', 'Fracture', 'Seizure', 'Overdose', 'Allergic reaction',
    'Stroke symptoms', 'Psychiatric crisis', 'OB/GYN emergency',
    'Pediatric fever', 'Back pain', 'Syncope', 'Burn', 'Eye injury',
    'Nosebleed', 'Foreign body', 'Medication refill'
  ]
  
  const firstNames = ['James', 'Maria', 'Robert', 'Jennifer', 'Michael', 'Linda', 'William', 'Elizabeth', 'David', 'Barbara', 'Richard', 'Susan', 'Joseph', 'Jessica', 'Thomas', 'Sarah', 'Charles', 'Karen', 'Christopher', 'Nancy']
  const lastNames = ['Smith', 'Johnson', 'Williams', 'Brown', 'Jones', 'Garcia', 'Miller', 'Davis', 'Rodriguez', 'Martinez', 'Hernandez', 'Lopez', 'Gonzalez', 'Wilson', 'Anderson', 'Thomas', 'Taylor', 'Moore', 'Jackson', 'Martin']

  const patients: Patient[] = []
  for (let i = 0; i < count; i++) {
    const esiLevel = (Math.floor(Math.random() * 5) + 1) as ESILevel
    const statuses: Patient['status'][] = ['waiting', 'in-progress', 'ready-for-disposition', 'discharged', 'admitted']
    const status = statuses[Math.floor(Math.random() * statuses.length)]
    
    patients.push({
      id: generateId(),
      name: `${firstNames[Math.floor(Math.random() * firstNames.length)]} ${lastNames[Math.floor(Math.random() * lastNames.length)]}`,
      age: Math.floor(Math.random() * 90) + 1,
      gender: Math.random() > 0.5 ? 'M' : 'F',
      chiefComplaint: complaints[Math.floor(Math.random() * complaints.length)],
      esiLevel,
      arrivalTime: `${String(Math.floor(Math.random() * 12) + 8).padStart(2, '0')}:${String(Math.floor(Math.random() * 60)).padStart(2, '0')}`,
      vitals: {
        bp: `${Math.floor(Math.random() * 40) + 100}/${Math.floor(Math.random() * 30) + 60}`,
        hr: Math.floor(Math.random() * 50) + 60,
        spo2: Math.floor(Math.random() * 10) + 90,
        temp: Math.round((Math.random() * 3 + 36.5) * 10) / 10,
        rr: Math.floor(Math.random() * 15) + 12,
      },
      assignedNurse: Math.random() > 0.3 ? `RN ${firstNames[Math.floor(Math.random() * firstNames.length)]} ${lastNames[Math.floor(Math.random() * lastNames.length)]}` : undefined,
      room: Math.random() > 0.4 ? `Room ${Math.floor(Math.random() * 10) + 1}` : undefined,
      notes: 'Auto-generated mock patient for demo purposes.',
      status,
      waitTimeMinutes: Math.floor(Math.random() * 120),
    })
  }
  return patients
}